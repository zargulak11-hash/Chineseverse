if __name__ == "__main__":
    db = SessionLocal()
    lvl = db.query(models.HSKLevel).filter_by(level=1).first()
    rows = db.query(models.Hanzi).filter_by(hsk_level_id=lvl.id).all()
    n, missing = 0, []
    for h in rows:
        pair = HANZI_RU_TG.get(h.character)
        if not pair:
            missing.append(h.character)
            continue
        ru, tg = pair
        set_translation(db, "hanzi", str(h.id), "meaning", "ru", ru)
        set_translation(db, "hanzi", str(h.id), "meaning", "tg", tg)
        n += 1
    db.commit()
    print(f"Translated {n}/{len(rows)} HSK1 Hanzi meanings (ru+tg).")
    if missing:
        print(f"Missing from dict (not translated, real gap to report): {missing}")
    db.close()
