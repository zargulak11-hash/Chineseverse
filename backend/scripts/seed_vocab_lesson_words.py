def main() -> None:
    from app import models
    from app.database import SessionLocal
    from app.services.lesson_path import ordered_lessons
    from app.services.practice import lesson_items

    db = SessionLocal()
    level_of = {l.id: l.level for l in db.query(models.HSKLevel)}
    ids = {f"{level_of[w.hsk_level_id]}|{w.simplified}": w.id for w in db.query(models.VocabularyWord)}
    unknown = [k for k in MEANINGS if k not in ids]
    if unknown:
        raise SystemExit(f"not vocabulary rows: {unknown}")
    have = {
        (t.content_key, t.locale)
        for t in db.query(models.ContentTranslation).filter_by(content_type="vocab_word", field="meanings")
    }
    added = 0
    for key, (ru, tg) in MEANINGS.items():
        for locale, text in (("ru", ru), ("tg", tg)):
            if (str(ids[key]), locale) not in have:
                db.add(models.ContentTranslation(
                    content_type="vocab_word", content_key=str(ids[key]), field="meanings", locale=locale, text=text,
                ))
                added += 1
    db.commit()
    # Every word a lesson teaches now has ru and tg.
    have = {
        (int(t.content_key), t.locale)
        for t in db.query(models.ContentTranslation).filter_by(content_type="vocab_word", field="meanings")
    }
    missing = sorted({
        w.simplified for lesson, _lvl in ordered_lessons(db) for w in lesson_items(db, lesson)["vocab"]
        if (w.id, "ru") not in have or (w.id, "tg") not in have
    })
    print(f"Added {added} ru/tg meanings; lesson words still without ru/tg: {missing}")


if __name__ == "__main__":
    main()
