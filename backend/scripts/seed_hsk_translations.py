def apply_category_translations(db):
    topics = db.query(models.GrammarTopic).filter(models.GrammarTopic.category.isnot(None)).all()
    n = 0
    for t in topics:
        pair = CATEGORY_RU_TG.get(t.category)
        if not pair:
            continue
        ru, tg = pair
        set_translation(db, "grammar_topic", str(t.id), "category", "ru", ru)
        set_translation(db, "grammar_topic", str(t.id), "category", "tg", tg)
        n += 1
    db.commit()
    return n


