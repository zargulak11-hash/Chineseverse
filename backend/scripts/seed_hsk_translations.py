def apply_lesson_title_translations(db):
    """Generated lesson titles look like 'HSK7 Grammar 3: 副词' -- translate
    the template word 'Grammar' (the category suffix already gets its own
    translation via `category`, and stays correct here since it's real
    Chinese either way)."""
    import re
    lessons = db.query(models.Lesson).filter(models.Lesson.lesson_type == "grammar").all()
    n = 0
    for l in lessons:
        m = re.match(r"^(HSK\d+) Grammar (\d+)(: .+)?$", l.title)
        if not m:
            continue
        level_part, idx, suffix = m.groups()
        suffix = suffix or ""
        set_translation(db, "lesson", str(l.id), "title", "ru", f"{level_part} Грамматика {idx}{suffix}")
        set_translation(db, "lesson", str(l.id), "title", "tg", f"{level_part} Грамматика {idx}{suffix}")
        n += 1
    db.commit()
    return n


